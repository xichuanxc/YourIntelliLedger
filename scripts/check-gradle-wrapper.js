#!/usr/bin/env node
/**
 * Fails fast when `android/gradle/wrapper/gradle-wrapper.properties` drifts
 * from the Gradle version React Native is built against.
 *
 * Android Studio upgrades the wrapper on its own — it did so twice here, on
 * 31 Jul and again on 3 Aug, both times bumping 9.3.1 to 9.6.1. Under the
 * newer Gradle the Kotlin compiler fails to build React Native's own Gradle
 * plugin with "Incompatible classes were found in dependencies", which
 * surfaces only as "Internal compiler error" after several minutes of
 * building. This check turns that into one line, immediately.
 *
 * The expected version is read from `@react-native/gradle-plugin`'s own
 * wrapper rather than hard-coded, so a React Native upgrade moves the
 * expectation automatically instead of leaving a stale constant behind.
 */

const fs = require('node:fs');
const path = require('node:path');

const projectRoot = path.resolve(__dirname, '..');
const projectWrapper = path.join(projectRoot, 'android/gradle/wrapper/gradle-wrapper.properties');
const referenceWrapper = path.join(
  projectRoot,
  'node_modules/@react-native/gradle-plugin/gradle/wrapper/gradle-wrapper.properties'
);

/** Pulls `9.3.1` out of a `distributionUrl=...gradle-9.3.1-bin.zip` line. */
function gradleVersionIn(file) {
  if (!fs.existsSync(file)) return null;
  const match = /distributionUrl=.*?gradle-([\d.]+)-(?:bin|all)\.zip/.exec(
    fs.readFileSync(file, 'utf8')
  );
  return match ? match[1] : null;
}

// No android/ yet is not a failure — it is generated by `expo prebuild`.
if (!fs.existsSync(projectWrapper)) process.exit(0);

const expected = gradleVersionIn(referenceWrapper);
const actual = gradleVersionIn(projectWrapper);

if (!expected) {
  // Reference missing (deps not installed, or React Native moved the file).
  // Don't block the build on a check that can no longer check anything.
  process.exit(0);
}

if (actual !== expected) {
  console.error(
    `\nGradle wrapper drift: android/ is on Gradle ${actual ?? 'an unreadable version'}, ` +
      `but React Native is built against ${expected}.\n\n` +
      `Android Studio does this on its own. Under the wrong version the Kotlin\n` +
      `compiler fails on React Native's Gradle plugin and reports only\n` +
      `"Internal compiler error", minutes into the build.\n\n` +
      `Fix it with either:\n` +
      `  npx expo prebuild --platform android --clean\n` +
      `  # or edit android/gradle/wrapper/gradle-wrapper.properties back to ${expected}\n\n` +
      `Then decline Android Studio's "Upgrade Gradle" prompt.\n`
  );
  process.exit(1);
}
